import type { InterviewGuide } from './interview-guide'

export const formatInterviewGuide = (guide: InterviewGuide): string => [
  `# ${guide.labels.title}: ${guide.role}${guide.company ? ` — ${guide.company}` : ''}`,
  '',
  `${guide.labels.quickReference} · profile ${guide.profileVersion}`,
  ...guide.quickReference.map((item) => `- ${item}`),
  '',
  `## ${guide.labels.introduction}`,
  guide.introduction,
  '',
  `## ${guide.labels.story}`,
  guide.story.contextPrompt,
  ...guide.story.evidence.map((item) => `- ${item}`),
  guide.story.outcomePrompt,
  '',
  `## ${guide.labels.questions}`,
  ...guide.questions.flatMap((item) => [`### ${item.question}`, ...item.talkingPoints.map((point) => `- ${point}`)]),
  '',
  `## ${guide.labels.ask}`,
  ...guide.questionsToAsk.map((question) => `- ${question}`),
  '',
  `## ${guide.labels.contingencies}`,
  ...guide.contingencies.flatMap((item) => [`### ${item.question}`, item.answer]),
  ...(guide.gaps.length ? ['', `## ${guide.labels.gaps}`, ...guide.gaps.map((gap) => `- ${gap}`)] : []),
  '',
  `## ${guide.labels.closing}`,
  guide.closing,
].join('\n')
